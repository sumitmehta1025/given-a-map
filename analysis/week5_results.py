"""Week 5 analysis: the tables and figures the plan promises (docs/07-experiment-plan.md §6–7).

Usage:
    .venv/bin/python analysis/week5_results.py analysis/output/runs1-3/attempts.csv \
        analysis/output/run1-with-D/attempts.csv --out analysis/output/week5

Input: one or more attempts.csv files from analyze_traces.py. A (run, setup, task) row that
appears in more than one file is counted once (the last file wins).

Writes to --out:
    results.md                 every table below, in Markdown
    resolution.csv             resolved per setup × run × group
    per_task.csv               solved count per task × setup (the appendix table)
    fig1_resolution.png        resolved per setup, one dot per run
    fig2_per_task.png          per-task heatmap: the task decides the outcome
    fig3_failures.png          failure mix per setup
    fig4_graph_use.png         how often each setup used the graph tools

Rule for a real difference (plan §7, locked Oct 17): same direction in all 3 runs, and
bigger than the spread between runs of the same setup.
"""
import argparse
import csv
from collections import Counter, defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from graph_lookup import changed_nodes, load_graph, load_task

ROOT = Path(__file__).resolve().parent.parent
SETUPS = {"Grep only": "A", "Graph + grep": "B", "Graph + grep, prompted": "C", "Graph required": "D"}
LABELS = {"A": "A: grep only", "B": "B: grep + graph", "C": "C: official sample", "D": "D: graph required"}
GROUPS = ["Multi-file", "Single-file"]
CATEGORIES = ["Crash or tool error", "Never found the code", "Found it, never edited",
              "Edited the wrong place", "Right place, wrong fix", "Fixed it, broke something", "Other"]
COMPARISONS = [("B", "A"), ("C", "A"), ("C", "B"), ("D", "A")]


def load(paths):
    rows = {}
    for path in paths:
        for r in csv.DictReader(open(path)):
            r["s"] = SETUPS[r["setup"]]
            r["ok"] = r["resolved"] == "1"
            rows[(r["run"], r["s"], r["task"])] = r
    return list(rows.values())


def md_table(header, body):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(lines)


def resolution(rows, setups, runs):
    """resolved[(setup, run, group)] and attempts[...]; group "All" included."""
    resolved, attempts = Counter(), Counter()
    for r in rows:
        for g in ("All", r["group"]):
            attempts[(r["s"], r["run"], g)] += 1
            resolved[(r["s"], r["run"], g)] += r["ok"]
    return resolved, attempts


def comparisons(rows, setups, runs):
    """Per pair, per run: difference in resolved on the tasks both setups ran in that run."""
    by = {(r["run"], r["s"], r["task"]): r["ok"] for r in rows}
    out = []
    for a, b in COMPARISONS:
        if a not in setups or b not in setups:
            continue
        diffs = {}
        for run in runs:
            tasks = [t for (rn, s, t) in by if rn == run and s == a and (run, b, t) in by]
            if tasks:
                diffs[run] = (sum(by[(run, a, t)] for t in tasks) - sum(by[(run, b, t)] for t in tasks), len(tasks))
        out.append((a, b, diffs))
    return out


def spread(resolved, s, runs):
    """Max − min resolved across runs; None with fewer than 2 runs (no spread to measure)."""
    vals = [resolved[(s, run, "All")] for run in runs if (s, run, "All") in resolved]
    return max(vals) - min(vals) if len(vals) > 1 else None


def blind_spots(tasks):
    """Functions the reference fix changed that have no edges in the task's graph."""
    changed = isolated = unmapped = 0
    for t in tasks:
        task = load_task(t)
        nodes, neighbors = load_graph(task)
        found = changed_nodes(task["patch"], nodes)
        unmapped += not found
        changed += len(found)
        isolated += sum(not neighbors[n] for n in found)
    return changed, isolated, unmapped


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("attempts", nargs="+")
    p.add_argument("--out", default=str(ROOT / "analysis" / "output" / "week5"))
    args = p.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    rows = load(args.attempts)
    setups = [s for s in "ABCD" if any(r["s"] == s for r in rows)]
    runs = sorted({r["run"] for r in rows})
    tasks = sorted({r["task"] for r in rows})
    group_of = {r["task"]: r["group"] for r in rows}
    resolved, attempts = resolution(rows, setups, runs)
    md = ["# Week 5 results", "",
          f"Generated by `analysis/week5_results.py` from {', '.join(f'`{a}`' for a in args.attempts)}. "
          f"{len(rows)} attempts, {len(tasks)} tasks. Don't edit by hand; re-run the script.", ""]

    # 1. Resolution per setup × run × group
    with open(out / "resolution.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["setup", "run", "group", "resolved", "attempts"])
        for s in setups:
            for run in runs:
                for g in ["All"] + GROUPS:
                    if attempts[(s, run, g)]:
                        w.writerow([s, run, g, resolved[(s, run, g)], attempts[(s, run, g)]])
    body = []
    for s in setups:
        cells = [f"{resolved[(s, run, 'All')]}/{attempts[(s, run, 'All')]}" if attempts[(s, run, "All")] else "–"
                 for run in runs]
        tot, n = sum(resolved[(s, r, "All")] for r in runs), sum(attempts[(s, r, "All")] for r in runs)
        multi = sum(resolved[(s, r, "Multi-file")] for r in runs), sum(attempts[(s, r, "Multi-file")] for r in runs)
        single = sum(resolved[(s, r, "Single-file")] for r in runs), sum(attempts[(s, r, "Single-file")] for r in runs)
        body.append([LABELS[s], *cells, f"**{tot}/{n} ({tot / n:.0%})**", "–" if spread(resolved, s, runs) is None else spread(resolved, s, runs),
                     f"{multi[0]}/{multi[1]}", f"{single[0]}/{single[1]}"])
    md += ["## 1. Resolved per setup and run", "",
           md_table(["Setup", *[f"Run {r}" for r in runs], "Total", "Spread (max − min)", "Multi-file", "Single-file"], body),
           "", "Spread = how much the same setup moves between runs. A gap between setups smaller than this is noise.", ""]

    # 2. Paired differences and the plan's rule
    body = []
    for a, b, diffs in comparisons(rows, setups, runs):
        signs = {(d > 0) - (d < 0) for d, _ in diffs.values()}
        same = len(diffs) == len(runs) and len(signs) == 1 and 0 not in signs
        widest = max(x for x in (spread(resolved, a, runs), spread(resolved, b, runs)) if x is not None)
        bigger = all(abs(d) > widest for d, _ in diffs.values())
        verdict = "✅ real" if same and bigger else "❌ noise"
        body.append([f"{a} − {b}", *[f"{diffs[r][0]:+d}" + ("" if diffs[r][1] == len(tasks) else f" ({diffs[r][1]} tasks)")
                                    if r in diffs else "–" for r in runs],
                     "yes" if same else "no", f"{'yes' if bigger else 'no'} (spread {widest})", verdict])
    md += ["## 2. Is any difference real? (plan §7 rule)", "",
           md_table(["Comparison", *[f"Run {r}" for r in runs], "Same direction every run?", "Bigger than spread?", "Verdict"], body),
           "", "Differences are counted on the tasks both setups ran in that run.", ""]

    # 3. The task decides the outcome
    solved = defaultdict(list)
    for r in rows:
        solved[r["task"]].append(r["ok"])
    kinds = Counter("never" if not any(v) else "always" if all(v) else "sometimes" for v in solved.values())
    outcomes = [o for v in solved.values() for o in v]
    mean = sum(outcomes) / len(outcomes)
    total_var = mean * (1 - mean)
    task_var = sum(len(v) * (sum(v) / len(v) - mean) ** 2 for v in solved.values()) / len(outcomes)
    setup_rates = {s: [r["ok"] for r in rows if r["s"] == s] for s in setups}
    setup_var = sum(len(v) * (sum(v) / len(v) - mean) ** 2 for v in setup_rates.values()) / len(outcomes)
    md += ["## 3. The task decides the outcome", "",
           md_table(["Solved in", "Tasks"], [["every attempt", kinds["always"]], ["some attempts", kinds["sometimes"]],
                                             ["no attempt", kinds["never"]]]), "",
           f"- **Share of the variation in outcomes explained by which task it was: {task_var / total_var:.0%}.** "
           f"By which setup: {setup_var / total_var:.1%}. (Descriptive: per-task rates come from only ~10 attempts each, so the task share is a little inflated.)",
           "- How to read it: if you know the task, you can almost always predict the result; knowing the setup tells you next to nothing.",
           ""]
    with open(out / "per_task.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["task", "group", *setups, "total", "attempts"])
        per_task = []
        for t in tasks:
            counts = [f"{sum(r['ok'] for r in ran)}/{len(ran)}" if (ran := [r for r in rows if r["task"] == t and r["s"] == s])
                      else "–" for s in setups]
            n = sum(1 for r in rows if r["task"] == t)
            total = sum(r["ok"] for r in rows if r["task"] == t)
            per_task.append((t, group_of[t], counts, total, n))
            w.writerow([t, group_of[t], *counts, total, n])
    per_task.sort(key=lambda x: (-x[3] / x[4], x[0]))
    md += ["### Appendix: solved count per task", "",
           md_table(["Task", "Group", *setups, "Total"],
                    [[t, g, *c, f"{tot}/{n}"] for t, g, c, tot, n in per_task]), ""]

    # 4. Failure mix (H3)
    fails = [r for r in rows if not r["ok"]]
    body = []
    for s in setups:
        f_s = [r for r in fails if r["s"] == s]
        c = Counter(r["category"] or "Other" for r in f_s)
        body.append([LABELS[s], len(f_s), *[c[k] for k in CATEGORIES],
                     f"{sum(r['hit_limit'] == 'Yes' for r in f_s)}/{len(f_s)}"])
    md += ["## 4. Why attempts failed (H3)", "",
           md_table(["Setup", "Failures", *CATEGORIES, "Hit the limit"], body), ""]

    # 5. Graph tool use
    body = []
    for s in setups:
        x = [r for r in rows if r["s"] == s]
        body.append([LABELS[s], len(x), sum(int(r["graph_tool_calls"]) for r in x),
                     sum(int(r["graph_tool_calls"]) > 0 for r in x),
                     sum(r["first_calls"].split(" > ")[0] == "search_similar_code" for r in x),
                     sum("get_code_neighbors" in r["first_calls"] for r in x),
                     f"{sum(float(r['agent_minutes']) for r in x) / len(x):.2f}",
                     f"{sum(int(r['tool_calls']) for r in x) / len(x):.1f}"])
    md += ["## 5. Did the agent use the graph tools?", "",
           md_table(["Setup", "Attempts", "Graph calls", "Attempts with any", "First call = search",
                     "Neighbors in first 2", "Avg. minutes", "Avg. calls"], body), ""]

    # 6. Blind spots (plan §7)
    changed, isolated, unmapped = blind_spots(tasks)
    md += ["## 6. Graph blind spots (plan §7)", "",
           f"- The reference fixes change **{changed}** functions or classes that the graph has a node for. "
           f"**{isolated}** of them have **no edges** (nothing calls them and they call nothing, as far as the graph knows).",
           f"- In **{unmapped}** of {len(tasks)} tasks, no changed line could be matched to a graph node (e.g. the fix adds new code, "
           "or changes lines outside any function or class).",
           "- So blind spots don't explain the null result: the graph covers almost every fix, but the agent rarely asks it.",
           ""]

    md += ["## 7. Sensitivity check (plan §7)", "",
           "The plan asked for results with and without the excluded tasks. All 26 tasks are checked solvable; "
           "the excluded ones can't pass even with the reference fix (Oct 21 validation), so including them would only "
           "add guaranteed failures to every setup. Not run; stated in the paper.", ""]
    (out / "results.md").write_text("\n".join(md))

    figures(rows, setups, runs, resolved, attempts, per_task, fails, out)
    print(f"Wrote {out}/results.md and 4 figures")


def figures(rows, setups, runs, resolved, attempts, per_task, fails, out):
    colors = {"A": "#7f7f7f", "B": "#1f77b4", "C": "#2ca02c", "D": "#d62728"}
    marks = ["o", "s", "^"]

    # Fig 1: resolved share per setup, one dot per run, bar = mean
    fig, ax = plt.subplots(figsize=(6, 3.5))
    for i, s in enumerate(setups):
        rates = [resolved[(s, r, "All")] / attempts[(s, r, "All")] for r in runs if attempts[(s, r, "All")]]
        ax.bar(i, sum(rates) / len(rates), color=colors[s], alpha=0.35, width=0.6)
        for j, rate in enumerate(rates):
            ax.scatter(i + (j - 1) * 0.12, rate, color=colors[s], marker=marks[j % 3], zorder=3,
                       label=f"Run {runs[j]}" if i == 0 else None)
    ax.set_xticks(range(len(setups)), [LABELS[s] for s in setups], fontsize=8)
    ax.set_ylabel("Share of tasks resolved")
    ax.set_ylim(0, 0.6)
    ax.legend(fontsize=7, loc="upper right")
    ax.set_title("Resolved per setup: the gaps are smaller than run-to-run spread", fontsize=9)
    fig.tight_layout()
    fig.savefig(out / "fig1_resolution.png", dpi=200)
    plt.close(fig)

    # Fig 2: per-task heatmap (share of runs solved), tasks sorted by overall solve rate
    data = []
    for t, g, _, _, _ in per_task:
        row = []
        for s in setups:
            v = [r["ok"] for r in rows if r["task"] == t and r["s"] == s]
            row.append(sum(v) / len(v) if v else float("nan"))
        data.append(row)
    fig, ax = plt.subplots(figsize=(4.2, 7))
    cmap_tasks = plt.get_cmap("Greens").copy()
    cmap_tasks.set_bad("#d9d9d9")  # not run yet
    im = ax.imshow(data, cmap=cmap_tasks, vmin=0, vmax=1, aspect="auto")
    ax.set_xticks(range(len(setups)), setups)
    ax.set_yticks(range(len(per_task)), [f"{t} {'(M)' if g == 'Multi-file' else ''}" for t, g, *_ in per_task],
                  fontsize=6)
    fig.colorbar(im, ax=ax, label="Share of runs solved", shrink=0.6)
    grey = " (grey = not run)" if any(v != v for row in data for v in row) else ""
    ax.set_title("Each row is one task (M = multi-file): most are\nall-or-nothing for every setup" + grey, fontsize=9)
    fig.tight_layout()
    fig.savefig(out / "fig2_per_task.png", dpi=200)
    plt.close(fig)

    # Fig 3: failure mix per setup (share of failures)
    fig, ax = plt.subplots(figsize=(6.5, 3.5))
    cmap = plt.get_cmap("tab10")
    for i, s in enumerate(setups):
        c = Counter(r["category"] or "Other" for r in fails if r["s"] == s)
        n, left = sum(c.values()), 0
        for k, cat in enumerate(CATEGORIES):
            w = c[cat] / n if n else 0
            ax.barh(i, w, left=left, color=cmap(k), label=cat if i == 0 else None)
            left += w
    ax.set_yticks(range(len(setups)), [f"{LABELS[s]} (n={sum(r['s'] == s for r in fails)})" for s in setups], fontsize=8)
    ax.invert_yaxis()
    ax.set_xlabel("Share of failed attempts")
    ax.legend(fontsize=6, ncol=2, loc="upper center", bbox_to_anchor=(0.5, -0.22))
    ax.set_title("Why attempts failed: finding the code is almost never the problem", fontsize=9)
    fig.tight_layout()
    fig.savefig(out / "fig3_failures.png", dpi=200)
    plt.close(fig)

    # Fig 4: graph tool use per setup
    fig, ax = plt.subplots(figsize=(6, 3.2))
    width = 0.38
    for i, s in enumerate(setups):
        x = [r for r in rows if r["s"] == s]
        any_graph = sum(int(r["graph_tool_calls"]) > 0 for r in x) / len(x)
        neighbors = sum("get_code_neighbors" in r["first_calls"] for r in x) / len(x)
        ax.bar(i - width / 2, any_graph, width, color=colors[s])
        ax.bar(i + width / 2, neighbors, width, color=colors[s], alpha=0.4, hatch="//")
        ax.text(i - width / 2, any_graph + 0.02, f"{any_graph:.0%}", ha="center", fontsize=7)
        ax.text(i + width / 2, neighbors + 0.02, f"{neighbors:.0%}", ha="center", fontsize=7, color="#555")
    ax.set_xticks(range(len(setups)), [LABELS[s] for s in setups], fontsize=8)
    ax.set_ylabel("Share of attempts")
    ax.set_ylim(0, 1)
    ax.bar(0, 0, color="k", label="used any graph tool")
    ax.bar(0, 0, color="k", alpha=0.4, hatch="//", label="called get_code_neighbors early")
    ax.legend(fontsize=7, loc="upper left")
    ax.set_title("Graph tools are used only when required, and then only once", fontsize=9)
    fig.tight_layout()
    fig.savefig(out / "fig4_graph_use.png", dpi=200)
    plt.close(fig)


if __name__ == "__main__":
    main()
